import Object from "./object";
import Animator from "./animator";

/**
 * Enemy types. `kind` picks the behaviour:
 *  - walker: patrols, and lunges at a player who comes close in front of it
 *  - flyer:  flies a wavy patrol and swoops down at a player below it
 *  - turret: stands still and spits seeds at a player in range
 * Width/height are the draw (and hit) size in world pixels.
 */
export const enemyTypes = {
  pig: { kind: "walker", maxV: 0.8, minV: 0.5, delay: 2, width: 21, height: 20, walk: 16 },
  slime: { kind: "walker", maxV: 0.4, minV: 0.2, delay: 4, width: 23, height: 20, walk: 10 },
  chameleon: { kind: "walker", maxV: 0.4, minV: 0.2, delay: 2, width: 22, height: 20, walk: 8 },
  beetle: {
    kind: "walker",
    maxV: 0.5,
    minV: 0.35,
    delay: 3,
    width: 20,
    height: 14,
    walk: 4,
    hp: 2,
    score: 200,
  },
  bat: { kind: "flyer", maxV: 0.9, minV: 0.6, delay: 2, width: 18, height: 12, walk: 4 },
  spitter: { kind: "turret", delay: 5, width: 16, height: 18, walk: 4, shoot: 3 },
};

const ATTACK_FRAMES = 4;
const DEATH_FRAMES = 8; // generated by scripts/generate-enemy-death.py
const DEATH_DELAY = 2;

// Attack timings (ticks at 30/s)
const WINDUP = 9; // telegraph: crouch and flash before the lunge
const LUNGE = 10;
const RECOVER = 24;
const LUNGE_SPEED = 2.6;
const SIGHT_X = 52; // how close (px, in front) before a walker attacks
const SPIT_EVERY = 80;
const SPIT_RANGE = 88; // the generator keeps spitters this far from portal arrivals

// Sprites are shared by every area, so they are loaded once, not per area.
let sharedFrames = null;
const loader = { assetCount: 0, loadCount: 0 };

const loadFrames = () => {
  if (sharedFrames) return sharedFrames;
  sharedFrames = {};

  const add = (key, src) => {
    const image = new Image();
    image.onload = image.onerror = () => {
      loader.loadCount += 1;
    };
    image.src = src;
    (sharedFrames[key] = sharedFrames[key] || []).push(image);
    loader.assetCount += 1;
  };

  const root = "./assets/sprites/enemies";
  // `Object` is the game-object class here, so use the global one
  globalThis.Object.keys(enemyTypes).forEach((id) => {
    const { walk, kind, shoot = 0 } = enemyTypes[id];
    ["left", "right"].forEach((side) => {
      const Side = side === "left" ? "Left" : "Right";
      for (let i = 1; i <= walk; i++)
        add(`${id}${Side}`, `${root}/${id}/${side}/image_part_0${i}.png`);
      for (let i = 1; i <= DEATH_FRAMES; i++)
        add(`${id}Dead${Side}`, `${root}/${id}/dead/${side}/image_part_0${i}.png`);
      if (kind === "walker")
        for (let i = 1; i <= ATTACK_FRAMES; i++)
          add(`${id}Attack${Side}`, `${root}/${id}/attack/${side}/image_part_0${i}.png`);
      for (let i = 1; i <= shoot; i++)
        add(`${id}Attack${Side}`, `${root}/${id}/attack/${side}/image_part_0${i}.png`);
    });
  });

  return sharedFrames;
};

export default class Enemies {
  constructor(enemies = [], tileSize = 16, killedEnemies = "") {
    this.items = [];
    this.frameSets = loadFrames();

    this.tileSize = tileSize;
    // ids are stored as "id1,id2,"; match whole ids, not substrings
    const killed = new Set(killedEnemies.split(","));
    for (let index = 0; index < enemies.length; index++) {
      if (!killed.has(enemies[index].id)) this.add(enemies[index]);
    }
  }

  /** Add an enemy from an area entry { id, type, left, top, sway, dir }. */
  add({ id, type, left, top, sway, dir }) {
    if (!enemyTypes[type]) return null;
    const f = this.frameSets;
    const enemy = new Enemy({
      id,
      type,
      x: left * this.tileSize,
      top,
      tileSize: this.tileSize,
      frames: [f[`${type}Left`], f[`${type}Right`]],
      attackFrames: [f[`${type}AttackLeft`], f[`${type}AttackRight`]],
      deathFrames: [f[`${type}DeadLeft`], f[`${type}DeadRight`]],
      sway,
      direction: dir,
    });
    this.items.push(enemy);
    return enemy;
  }

  get assetCount() {
    return loader.assetCount;
  }

  get loadCount() {
    return loader.loadCount;
  }

  get loaded() {
    return loader.loadCount >= loader.assetCount;
  }

  /** Enemies that can still hurt the player or be hit. */
  get alive() {
    return this.items.filter((enemy) => !enemy.dying);
  }

  remove(enemy) {
    const index = this.items.indexOf(enemy);
    if (index >= 0) this.items.splice(index, 1);
  }

  /** `player` (optional) drives attacks; `spit(x, y, dir)` fires a seed. */
  update(player, spit) {
    for (let index = 0; index < this.items.length; index++) {
      this.items[index].update(player, spit);
    }
    // drop enemies whose death animation has finished
    this.items = this.items.filter((enemy) => !enemy.dead);
  }

  updateAnimation() {
    for (let index = 0; index < this.items.length; index++) {
      this.items[index].updateAnimation();
    }
  }
}

export class Enemy extends Object {
  constructor({
    id,
    type,
    x,
    top,
    tileSize = 16,
    frames,
    attackFrames = [],
    deathFrames = [],
    sway = 24,
    direction = 1,
  }) {
    const config = enemyTypes[type] || enemyTypes.pig;
    const { width, height, delay = 2, maxV = 0, minV = 0, kind, hp = 1 } = config;

    // walkers and turrets stand on the tile below `top`; flyers hover in it
    const y = kind === "flyer" ? top * tileSize + 2 : (top + 1) * tileSize - height;
    super(x, y, width, height);

    this.id = id;
    this.type = type;
    this.kind = kind;
    this.score = config.score || 100;
    this.hp = hp;
    this.sway = sway;
    this.frameSets = frames;
    this.attackFrameSets = attackFrames;
    this.deathFrameSets = deathFrames;
    // kept for tests and older callers
    this.deathFrames = deathFrames;

    this.baseX = x;
    this.baseY = y;
    this.delay = delay;
    this.direction = direction < 0 ? -1 : 1;
    this.velocity = Math.random() * (maxV - minV) + minV;

    this.state = "patrol"; // patrol | windup | lunge | recover | spit
    this.stateTimer = 0;
    this.phase = Math.random() * Math.PI * 2;
    this.spitTimer = SPIT_EVERY / 2 + Math.floor(Math.random() * SPIT_EVERY);
    this.flash = 0; // white flash when an armoured enemy takes a hit

    this.dying = false; // hit, playing the death animation
    this.dead = false; // death animation finished; remove from the world
    this.knockback = 0;

    this.animator = new Animator(this.walkFrames(), delay);
  }

  walkFrames() {
    return this.frameSets[this.direction < 0 ? 0 : 1];
  }

  attackFrames() {
    const set = this.attackFrameSets[this.direction < 0 ? 0 : 1];
    return set && set.length ? set : this.walkFrames();
  }

  /** Is the player close enough, in front, and at about the same height? */
  sees(player, range) {
    if (!player || player.deadTimer > 0) return false;
    const dx = player.getCenterX() - this.getCenterX();
    const dy = player.getBottom() - this.getBottom();
    return Math.abs(dx) <= range && Math.sign(dx || 1) === this.direction && Math.abs(dy) < 14;
  }

  setState(state, ticks) {
    this.state = state;
    this.stateTimer = ticks;
    if (state === "windup" || state === "spit") {
      // 4 frames over wind-up + lunge: crouch, flash, lunge, bite
      this.animator.changeFrameSet(this.attackFrames(), 3);
    } else if (state === "patrol" || state === "recover") {
      this.animator.changeFrameSet(this.walkFrames(), this.delay);
    }
  }

  get attacking() {
    return this.state === "windup" || this.state === "lunge";
  }

  /**
   * A fireball hit. Returns true if this killed it (armoured enemies take two).
   * `fromDirection` is the way the fireball was flying.
   */
  hit(fromDirection = 1) {
    if (this.dying) return false;
    this.hp -= 1;
    if (this.hp > 0) {
      this.flash = 8;
      this.knockback = 3 * (fromDirection < 0 ? -1 : 1);
      this.setState("recover", RECOVER);
      return false;
    }
    return this.kill(fromDirection);
  }

  /** Start the death animation. */
  kill(fromDirection = 1) {
    if (this.dying) return false;

    this.dying = true;
    this.hp = 0;
    this.knockback = 2.2 * (fromDirection < 0 ? -1 : 1);
    const frames = this.deathFrameSets && this.deathFrameSets[this.direction < 0 ? 0 : 1];
    if (frames && frames.length) {
      this.animator.changeFrameSet(frames, DEATH_DELAY);
    } else {
      this.dead = true;
    }
    return true;
  }

  turn(direction) {
    if (direction === this.direction) return;
    this.direction = direction;
    const frames =
      this.state === "windup" || this.state === "spit" ? this.attackFrames() : this.walkFrames();
    this.animator.changeFrameSet(frames, this.delay);
  }

  update(player, spit) {
    if (this.flash > 0) this.flash -= 1;
    if (this.knockback) {
      this.x += this.knockback;
      this.knockback *= 0.7;
      if (Math.abs(this.knockback) < 0.05) this.knockback = 0;
    }
    if (this.dying) return;

    if (this.kind === "turret") return this.updateTurret(player, spit);
    if (this.kind === "flyer") return this.updateFlyer(player);
    return this.updateWalker(player);
  }

  // keep inside the patrol range (+ a little extra while lunging)
  clamp(extra = 0) {
    const min = this.baseX - this.sway - extra;
    const max = this.baseX + this.sway + extra;
    if (this.x < min) this.x = min;
    if (this.x > max) this.x = max;
  }

  updateWalker(player) {
    if (this.stateTimer > 0) this.stateTimer -= 1;

    switch (this.state) {
      case "windup":
        if (this.stateTimer <= 0) this.setState("lunge", LUNGE);
        return;
      case "lunge":
        this.x += LUNGE_SPEED * this.direction;
        this.clamp(10);
        if (this.stateTimer <= 0) this.setState("recover", RECOVER);
        return;
      case "recover":
        // back toward the patrol range at walking pace
        if (this.x > this.baseX + this.sway) this.x -= this.velocity;
        else if (this.x < this.baseX - this.sway) this.x += this.velocity;
        if (this.stateTimer <= 0) this.setState("patrol", 0);
        return;
      default:
        break;
    }

    if (this.sees(player, SIGHT_X)) {
      this.setState("windup", WINDUP);
      return;
    }

    this.x += this.velocity * this.direction;
    if (this.x > this.baseX + this.sway) this.turn(-1);
    else if (this.x <= this.baseX - this.sway) this.turn(1);
  }

  updateFlyer(player) {
    this.phase += 0.12;
    if (this.stateTimer > 0) this.stateTimer -= 1;

    if (this.state === "lunge") {
      // swoop: dive toward where the player was, then climb back
      const t = 1 - this.stateTimer / 24;
      this.x += this.velocity * 2.2 * this.direction;
      this.y = this.baseY + Math.sin(t * Math.PI) * this.swoopDepth;
      this.clamp(16);
      if (this.stateTimer <= 0) {
        this.y = this.baseY;
        this.setState("recover", RECOVER * 2);
      }
      return;
    }

    if (this.state === "patrol" && player && player.deadTimer === 0) {
      const dx = player.getCenterX() - this.getCenterX();
      const dy = player.getCenterY() - this.getCenterY();
      if (Math.abs(dx) < 56 && dy > 8 && dy < 64 && Math.sign(dx || 1) === this.direction) {
        this.swoopDepth = Math.min(64, dy + 4);
        this.setState("lunge", 24);
        return;
      }
    }
    if (this.state === "recover" && this.stateTimer <= 0) this.setState("patrol", 0);

    this.x += this.velocity * this.direction;
    this.y = this.baseY + Math.sin(this.phase) * 4;
    if (this.x > this.baseX + this.sway) this.turn(-1);
    else if (this.x <= this.baseX - this.sway) this.turn(1);
  }

  updateTurret(player, spit) {
    if (player && player.deadTimer === 0) {
      const dx = player.getCenterX() - this.getCenterX();
      if (Math.abs(dx) < SPIT_RANGE) this.turn(dx < 0 ? -1 : 1);
    }

    if (this.state === "spit") {
      this.stateTimer -= 1;
      // the seed leaves the mouth mid-animation
      if (this.stateTimer === 3 && spit) {
        spit(this.getCenterX() + this.direction * 6, this.y + 6, this.direction);
      }
      if (this.stateTimer <= 0) this.setState("patrol", 0);
      return;
    }

    if (this.spitTimer > 0) this.spitTimer -= 1;
    if (this.spitTimer <= 0 && player && player.deadTimer === 0) {
      const dx = player.getCenterX() - this.getCenterX();
      const dy = player.getBottom() - this.getBottom();
      if (Math.abs(dx) < SPIT_RANGE && Math.abs(dy) < 40) {
        this.spitTimer = SPIT_EVERY;
        this.setState("spit", 9);
      }
    }
  }

  updateAnimation() {
    if (this.dying) {
      if (this.animator.frameIndex === this.animator.frameSet.length - 1) {
        // hold the last frame for one full step, then disappear
        this.holdLast = (this.holdLast || 0) + 1;
        if (this.holdLast > DEATH_DELAY) this.dead = true;
        return;
      }
      this.animator.animate(true);
      return;
    }
    // attack poses play once and hold
    this.animator.animate(
      this.state === "windup" || this.state === "lunge" || this.state === "spit",
    );
  }

  /** Where to draw the current frame (death frames are 2x the sprite, see the generator). */
  drawRect() {
    if (this.dying) {
      return {
        x: this.x - this.width * 0.5,
        y: this.y + 1 - this.height * 0.75,
        width: this.width * 2,
        height: this.height * 2,
      };
    }
    return { x: this.x, y: this.y + 1, width: this.width, height: this.height };
  }
}
